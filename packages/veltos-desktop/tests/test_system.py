import sys
import tempfile
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent


def load(name, path):
    loader = importlib.machinery.SourceFileLoader(name, str(path))
    spec = importlib.util.spec_from_loader(name, loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


app_names = load("update_app_names", PKG / "system/update-app-names")
session_defaults = load("session_defaults", PKG / "system/session-defaults")
fluent = load("fluent", PKG / "tools/fluent.py")

DOLPHIN = """\
[Desktop Entry]
Type=Application
Exec=dolphin %u
Icon=system-file-manager
Name=Dolphin
Name[tr]=Dolphin
GenericName=File Manager
GenericName[tr]=Dosya Yöneticisi
Keywords=files;file management
Keywords[tr]=dosyalar;dosya yönetimi;
Actions=new-window;

[Desktop Action new-window]
Name=Open a New Window
Name[tr]=Yeni Pencere Aç
Exec=dolphin %u
"""

VIM = """\
[Desktop Entry]
Name=Vim
Exec=vim %F
NoDisplay=false
Type=Application
"""


class AppNameTests(unittest.TestCase):
    def test_rename_keeps_actions_and_merges_keywords(self):
        text = app_names.rewrite(DOLPHIN, "dolphin",
                                 ("File Explorer", "Dosya Gezgini", "Explorer;Files;Gezgin;Dosyalar;"))
        main, action = text.split("[Desktop Action new-window]")
        self.assertIn("\nName=File Explorer\n", main)
        self.assertIn("\nName[tr]=Dosya Gezgini\n", main)
        self.assertNotIn("Name=Dolphin", main)
        self.assertIn("Name=Open a New Window", action)
        self.assertIn("Name[tr]=Yeni Pencere Aç", action)
        # Old name and Windows words are search keywords in every language.
        self.assertIn("Keywords=files;file management;Explorer;", main)
        self.assertIn("Dolphin;", main.split("Keywords=", 1)[1].splitlines()[0])
        self.assertIn("Keywords[tr]=dosyalar;dosya yönetimi;Explorer;", main)
        self.assertNotIn("GenericName", main)
        self.assertTrue(text.startswith("# Generated by veltos-desktop"))

    def test_hide_replaces_nodisplay(self):
        text = app_names.rewrite(VIM, "vim", hide=True)
        self.assertEqual(text.count("NoDisplay="), 1)
        self.assertIn("NoDisplay=true", text)

    def test_keywords_added_when_missing(self):
        text = app_names.rewrite(VIM, "vim", ("Text", "Metin", "Notepad;"))
        self.assertIn("Keywords=Notepad;Vim;", text)

    def test_file_without_name_is_rejected(self):
        with self.assertRaises(ValueError):
            app_names.rewrite("[Desktop Entry]\nExec=x\n", "x", hide=True)

    def test_update_writes_installed_apps_and_drops_stale(self):
        with tempfile.TemporaryDirectory() as tmp:
            src, out = Path(tmp) / "src", Path(tmp) / "out"
            src.mkdir()
            out.mkdir()
            (src / "org.kde.dolphin.desktop").write_text(DOLPHIN, encoding="utf-8")
            (src / "vim.desktop").write_text(VIM, encoding="utf-8")
            (src / "winetricks.desktop").write_text("[Desktop Entry]\nExec=x\n", encoding="utf-8")
            (out / "old-app.desktop").write_text("stale")
            (out / "org.kde.kate.desktop").write_text("kate was removed")
            written = app_names.update(src, out)
            self.assertEqual(sorted(written), ["org.kde.dolphin.desktop", "vim.desktop"])
            self.assertEqual(sorted(p.name for p in out.iterdir()),
                             ["org.kde.dolphin.desktop", "vim.desktop"])

    def test_kde_file_manager_and_control_panel_hidden(self):
        # VeltOS File Explorer and VeltOS Settings replace them in Start.
        self.assertIn("org.kde.dolphin.desktop", app_names.HIDE)
        self.assertIn("systemsettings.desktop", app_names.HIDE)

    def test_lists_do_not_overlap(self):
        self.assertFalse(set(app_names.APPS) & set(app_names.HIDE))


class SessionDefaultsTests(unittest.TestCase):
    def run_defaults(self, home, extra_env=None):
        env = {"HOME": str(home), "PATH": "/nonexistent"}
        env.update(extra_env or {})
        subprocess.run([sys.executable, str(PKG / "system/session-defaults")], env=env, check=True)

    def test_creates_style_and_places_once(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp)
            (home / ".config").mkdir()
            (home / ".config/user-dirs.dirs").write_text(
                'XDG_DOWNLOAD_DIR="$HOME/İndirilenler"\nXDG_DESKTOP_DIR="$HOME/Masaüstü"\n',
                encoding="utf-8")
            self.run_defaults(home)
            kvantum = home / ".config/Kvantum/kvantum.kvconfig"
            self.assertEqual(kvantum.read_text(), f"[General]\ntheme={fluent.KVANTUM_DIR}\n")
            places = home / ".local/share/user-places.xbel"
            tree = ET.parse(places)
            hrefs = [b.get("href") for b in tree.getroot().iter("bookmark")]
            self.assertEqual(hrefs[0], home.as_uri())
            self.assertIn((home / "İndirilenler").as_uri(), hrefs)
            self.assertEqual(hrefs[-1], "trash:/")
            self.assertEqual(len(hrefs), 8)
            view = home / ".local/share/dolphin/view_properties/global/.directory"
            self.assertIn("ViewMode=1", view.read_text())
            text = places.read_text(encoding="utf-8")
            self.assertIn("<GroupState-Remote-IsHidden>true</GroupState-Remote-IsHidden>", text)
            self.assertIn("<withRecentlyUsed>true</withRecentlyUsed>", text)
            # A second session keeps the user's own choices.
            kvantum.write_text("[General]\ntheme=Mine\n")
            places.write_text("mine")
            self.run_defaults(home)
            self.assertEqual(kvantum.read_text(), "[General]\ntheme=Mine\n")
            self.assertEqual(places.read_text(), "mine")

    def test_templates_and_public_folders_switched_off(self):
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp)
            (home / ".config").mkdir()
            (home / "Templates").mkdir()
            (home / "Public").mkdir()
            (home / "Public/shared.txt").write_text("keep")
            (home / ".config/user-dirs.dirs").write_text(
                'XDG_DESKTOP_DIR="$HOME/Desktop"\nXDG_TEMPLATES_DIR="$HOME/Templates"\n'
                'XDG_PUBLICSHARE_DIR="$HOME/Public"\n', encoding="utf-8")
            self.run_defaults(home)
            dirs = (home / ".config/user-dirs.dirs").read_text(encoding="utf-8")
            self.assertIn('XDG_TEMPLATES_DIR="$HOME/"', dirs)
            self.assertIn('XDG_PUBLICSHARE_DIR="$HOME/"', dirs)
            self.assertIn('XDG_DESKTOP_DIR="$HOME/Desktop"', dirs)
            self.assertFalse((home / "Templates").exists())
            self.assertTrue((home / "Public/shared.txt").exists())  # not empty: kept

    def test_theme_name_matches_package(self):
        self.assertEqual(session_defaults.KVANTUM_THEME, fluent.KVANTUM_DIR)


class SessionScriptTests(unittest.TestCase):
    SCRIPT = PKG / "system/veltos-session.sh"

    def data_dirs(self, initial):
        env = {"HOME": tempfile.mkdtemp(), "PATH": "/usr/bin:/bin"}
        if initial is not None:
            env["XDG_DATA_DIRS"] = initial
        # Twice: sourcing again must not add the directory again.
        out = subprocess.run(["sh", "-c", f". {self.SCRIPT}; . {self.SCRIPT}; echo $XDG_DATA_DIRS"],
                             env=env, capture_output=True, text=True, check=True)
        return out.stdout.strip()

    def languages(self, environment):
        env = {"HOME": tempfile.mkdtemp(), "PATH": "/usr/bin:/bin", **environment}
        out = subprocess.run(["sh", "-c", f". {self.SCRIPT}; . {self.SCRIPT}; echo $LANGUAGE"],
                             env=env, capture_output=True, text=True, check=True)
        return out.stdout.strip()

    def test_program_name_catalogs_come_first(self):
        self.assertEqual(self.languages({"LANG": "tr_TR.UTF-8"}), "tr@veltos:tr")
        self.assertEqual(self.languages({"LANGUAGE": "tr:en_US", "LANG": "tr_TR.UTF-8"}),
                         "tr@veltos:tr:en_US")
        self.assertEqual(self.languages({"LANG": "en_US.UTF-8"}), "en@veltos:en_US")
        self.assertEqual(self.languages({"LANG": "de_DE.UTF-8"}), "")

    def source(self, home):
        env = {"HOME": str(home), "PATH": "/usr/bin:/bin", "VELTOS_DESKTOP_ICONS": str(PKG / "desktop")}
        subprocess.run(["sh", "-c", f". {self.SCRIPT}"], env=env, check=True, capture_output=True)

    def test_gtk_programs_get_the_veltos_theme(self):
        home = Path(tempfile.mkdtemp())
        self.source(home)
        for gtk in ("gtk-3.0", "gtk-4.0"):
            self.assertIn("gtk-theme-name=VeltOS\n", (home / ".config" / gtk / "settings.ini").read_text())
        ini = home / ".config/gtk-3.0/settings.ini"
        ini.write_text("[Settings]\ngtk-theme-name=Breeze\ngtk-font-name=Inter 10\n")
        self.source(home)
        self.assertEqual(ini.read_text(), "[Settings]\ngtk-theme-name=VeltOS\ngtk-font-name=Inter 10\n")
        ini.write_text("[Settings]\ngtk-theme-name=Adwaita\n")       # the user's choice
        self.source(home)
        self.assertEqual(ini.read_text(), "[Settings]\ngtk-theme-name=Adwaita\n")

    def test_this_pc_and_recycle_bin_come_back(self):
        home = Path(tempfile.mkdtemp())
        (home / ".config").mkdir()
        (home / ".config/user-dirs.dirs").write_text('XDG_DESKTOP_DIR="$HOME/Masaüstü"\n', encoding="utf-8")
        self.source(home)
        desktop = home / "Masaüstü"
        self.assertEqual(sorted(p.name for p in desktop.iterdir()), ["recycle-bin.desktop", "this-pc.desktop"])
        self.assertTrue(os.access(desktop / "this-pc.desktop", os.X_OK))
        (desktop / "this-pc.desktop").unlink()
        self.source(home)
        self.assertTrue((desktop / "this-pc.desktop").exists())

    def test_desktop_icons(self):
        this_pc = (PKG / "desktop/this-pc.desktop").read_text()
        self.assertIn("Exec=veltos-explorer thispc:", this_pc)
        bin_entry = (PKG / "desktop/recycle-bin.desktop").read_text()
        self.assertIn("URL=trash:/", bin_entry)
        for text in (this_pc, bin_entry):
            self.assertRegex(text, r"Name\[tr\]=\S")

    def test_veltos_names_come_first(self):
        self.assertEqual(self.data_dirs(None), "/var/lib/veltos/xdg:/usr/local/share:/usr/share")
        self.assertEqual(self.data_dirs("/usr/share:/opt/x"), "/var/lib/veltos/xdg:/usr/share:/opt/x")


if __name__ == "__main__":
    unittest.main()
