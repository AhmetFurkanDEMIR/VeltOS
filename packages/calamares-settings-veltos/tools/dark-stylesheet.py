#!/usr/bin/python3
"""Make the installer's dark style sheet from the light one.

    dark-stylesheet.py LIGHT.qss DARK.qss

The installer follows the live session's light or dark theme (product
owner, 2026-10-23). Calamares' C++ pages (partitions, dialogs) are styled
by the branding style sheet; this maps every colour of the light sheet to
its dark counterpart, so the two cannot drift apart. White stays white as
the text colour of accent buttons and selections; the accent itself
(#2F5EE6 and its border #2A55D4) is left for start-calamares, which puts
the user's accent colour in. A colour without a mapping stops the build.
"""
import re
import sys

ACCENT = {"#2F5EE6", "#2A55D4"}
TERMINAL = {"#0C0C0C", "#CCCCCC", "#2B2B2B", "#264F78"}   # the failed-step log box
DARK = {
    "#F3F5FA": "#1C1E24",   # window
    "#FFFFFF": "#2A2C33",   # cards, fields, buttons
    "#F7F8FC": "#31343C",   # hover
    "#EEF1F7": "#383B44",   # pressed
    "#F1F3F9": "#31343C",   # hover fill
    "#F7F8FB": "#26282F",   # disabled
    "#FAFBFD": "#2D2F36",   # alternate rows
    "#1B1D24": "#F3F4F8",   # text
    "#5D6475": "#A9AFBD",   # secondary text
    "#A3A9B8": "#6C7282",   # disabled text
    "#8A90A2": "#80869A",   # control outlines
    "#E3E6EE": "#383B44",   # borders
    "#D5DAE5": "#4A4E59",   # control borders
    "#C3C9D6": "#5A5F6B",   # control bottom edges, scroll bars
    "#E4E8F3": "#3A3E4A",   # selected rows
    "#E1E5EE": "#3A3D46",   # progress track
    "#D7DCE8": "#3A3D46",   # installation progress track
}
IMAGES = {"chevron-down.svg": "chevron-down-dark.svg"}
DECLARATION = re.compile(r"(?P<prop>[a-z-]+)\s*:\s*(?P<value>[^;{}]+);")
COLOUR = re.compile(r"#[0-9A-Fa-f]{6}\b")


def dark_value(prop, value):
    def swap(match):
        colour = match.group(0).upper()
        if colour in ACCENT or colour in TERMINAL:
            return colour
        if colour == "#FFFFFF" and prop in ("color", "selection-color"):
            return colour                       # text on the accent
        if colour not in DARK:
            raise SystemExit(f"dark-stylesheet: no dark colour for {colour} ({prop})")
        return DARK[colour]
    value = COLOUR.sub(swap, value)
    for light, dark in IMAGES.items():
        value = value.replace("/" + light, "/" + dark)
    return value


def convert(text):
    def declaration(match):
        prop, value = match.group("prop"), match.group("value")
        return f"{prop}: {dark_value(prop, value)};"
    body = DECLARATION.sub(declaration, text)
    return body.replace("light Windows 11 style controls", "dark Windows 11 style controls", 1)


def main(argv):
    with open(argv[1], encoding="utf-8") as source:
        text = source.read()
    with open(argv[2], "w", encoding="utf-8", newline="\n") as target:
        target.write("/* Generated by tools/dark-stylesheet.py from stylesheet-light.qss. */\n")
        target.write(convert(text))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
