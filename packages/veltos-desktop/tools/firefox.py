"""VeltOS look for Firefox: Windows 11 caption buttons in the tab strip.

On Linux Firefox draws its own title bar buttons (round, libadwaita style)
instead of using the GTK theme, so the VeltOS GTK theme does not reach
them (VM test, 2026-10-20). Firefox's autoconfig (a privileged script named
by a default preference) registers a user style sheet that gives the
buttons the size, glyphs and hover colours of the VeltOS window frames
(tools/fluent.py). Users' own Firefox settings are not touched.

    usr/lib/firefox-esr/defaults/pref/veltos.js   general.config.* prefs
    usr/lib/firefox-esr/veltos.cfg                registers the style sheet
    usr/share/veltos/firefox/caption-buttons.css  the style sheet

VeltOS Mail was Thunderbird in Outlook's look until 2026-10-23 (its
autoconfig lived here); it is its own app now (packages/veltos-mail).
"""

import base64
import shutil
from pathlib import Path

import fluent

CSS_PATH = Path("usr/share/veltos/firefox/caption-buttons.css")
GLYPHS = {"titlebar-min": "minimize", "titlebar-max": "maximize",
          "titlebar-restore": "restore", "titlebar-close": "close"}


def glyph_uri(kind, colour):
    """The caption glyph alone (46 x 32) in one colour. Firefox does not
    let data: images take the text colour (context-stroke), so there is
    one image per colour: light theme, dark theme, and white on red."""
    w, h = fluent.CAPTION_W, fluent.CAPTION_H
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
           f'viewBox="0 0 {w} {h}">{fluent.caption_glyph(kind, 0, colour)}</svg>')
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode()).decode()


def caption_css():
    w, h = fluent.CAPTION_W, fluent.CAPTION_H
    light = fluent.CAPTION_COLOURS["light"]["glyph"]
    dark = fluent.CAPTION_COLOURS["dark"]["glyph"]
    lines = [
        '@namespace url("http://www.mozilla.org/keymaster/gatekeeper/there.is.only.xul");',
        "/* VeltOS: Windows 11 caption buttons (generated by tools/firefox.py). */",
        ".titlebar-buttonbox { --titlebar-button-spacing: 0px !important;",
        "  --titlebar-button-end-spacing: 0px !important; align-items: stretch !important; }",
        f".titlebar-button {{ padding: 0 !important; min-width: {w}px !important; }}",
        ".titlebar-button > .toolbarbutton-icon {",
        f"  width: {w}px !important; height: 100% !important; min-height: {h}px !important;",
        "  border-radius: 0 !important; background-color: transparent !important;",
        f"  background-size: {w}px {h}px !important; transition: none !important; }}",
        ":root:-moz-window-inactive .titlebar-button > .toolbarbutton-icon { opacity: 0.55; }",
        ".titlebar-button:hover > .toolbarbutton-icon {",
        "  opacity: 1; background-color: color-mix(in srgb, currentColor 9%, transparent) !important; }",
        ".titlebar-button:hover:active > .toolbarbutton-icon {",
        "  background-color: color-mix(in srgb, currentColor 5%, transparent) !important; }",
        ".titlebar-close:hover > .toolbarbutton-icon {",
        f"  background-color: {fluent.CLOSE_RED} !important; }}",
        ".titlebar-close:hover:active > .toolbarbutton-icon {",
        f"  background-color: color-mix(in srgb, {fluent.CLOSE_RED} 85%, transparent) !important; }}",
    ]
    dark_rules = []
    for cls, kind in GLYPHS.items():
        lines.append(f'.{cls} > .toolbarbutton-icon {{ background-image: url("{glyph_uri(kind, light)}") !important; }}')
        dark_rules.append(f'  .{cls} > .toolbarbutton-icon {{ background-image: url("{glyph_uri(kind, dark)}") !important; }}')
    lines += ["@media (prefers-color-scheme: dark) {", *dark_rules, "}"]
    lines.append(f'.titlebar-close:hover > .toolbarbutton-icon {{ background-image: url("{glyph_uri("close", "#ffffff")}") !important; }}')
    return "\n".join(lines) + "\n"


AUTOCONFIG_PREFS = """// VeltOS: run /usr/lib/firefox-esr/veltos.cfg at start-up (Firefox autoconfig).
pref("general.config.filename", "veltos.cfg");
pref("general.config.obscure_value", 0);
pref("general.config.sandbox_enabled", false);
// VeltOS: file dialogs through the desktop portal, i.e. VeltOS File
// Explorer's Windows 11 style dialog (1 = always; 2, the default, only in
// a sandbox or with GTK_USE_PORTAL).
pref("widget.use-xdg-desktop-portal.file-picker", 1);
"""

def autoconfig(what, sheets, extra=""):
    """The autoconfig script: registers `sheets` (file paths) as user style
    sheets for every window, then runs `extra` (more privileged JS)."""
    names = ", ".join(f'"file://{sheet}"' for sheet in sheets)
    return f"""// VeltOS {what} set-up (first line must be a comment).
// Registers the VeltOS style sheets for every window.
try {{
  let sss = Components.classes["@mozilla.org/content/style-sheet-service;1"]
      .getService(Components.interfaces.nsIStyleSheetService);
  let io = Components.classes["@mozilla.org/network/io-service;1"]
      .getService(Components.interfaces.nsIIOService);
  for (let sheet of [{names}]) {{
    let uri = io.newURI(sheet);
    if (!sss.sheetRegistered(uri, sss.USER_SHEET)) {{
      sss.loadAndRegisterSheet(uri, sss.USER_SHEET);
    }}
  }}
}} catch (e) {{
  Components.utils.reportError("VeltOS: " + e);
}}
{extra}"""


CAPTION_CSS = "/" + CSS_PATH.as_posix()
# Firefox's downloads panel in the Windows 11 look (firefox/downloads.css).
DOWNLOADS_CSS = "/usr/share/veltos/firefox/downloads.css"
AUTOCONFIG = autoconfig("Firefox", [CAPTION_CSS, DOWNLOADS_CSS])


def build(root):
    css = root / CSS_PATH
    css.parent.mkdir(parents=True, exist_ok=True)
    css.write_text(caption_css(), encoding="utf-8", newline="\n")
    prefs = root / "usr/lib/firefox-esr/defaults/pref/veltos.js"
    prefs.parent.mkdir(parents=True, exist_ok=True)
    prefs.write_text(AUTOCONFIG_PREFS, encoding="utf-8", newline="\n")
    (root / "usr/lib/firefox-esr/veltos.cfg").write_text(AUTOCONFIG, encoding="utf-8", newline="\n")
    downloads_css = root / DOWNLOADS_CSS.lstrip("/")
    shutil.copy(Path(__file__).resolve().parent.parent / "firefox/downloads.css", downloads_css)


if __name__ == "__main__":
    import sys
    build(Path(sys.argv[1]))
