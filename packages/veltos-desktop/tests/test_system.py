class AppNameTests(unittest.TestCase):
    def test_rename_keeps_actions_and_merges_keywords(self):
        text = app_names.rewrite(DOLPHIN, "dolphin",
                                 ("File Explorer", "Dosya Gezgini", "Explorer;Files;Gezgin;Dosyalar;"))
        main, action = text.split("[Desktop Action new-window]")
        self.assertIn("\nName=File Explorer\n", main)
        self.assertIn("\nName[tr]=Dosya Gezgini\n", main)
        self.assertNotIn("Name=Dolphin", main)
        self.assertIn("Name=Open a New Window", action)
        self.assertIn("Name[tr]=Yeni Pencere Aç", action)
        # Old name and Windows words are search keywords in every language.
        self.assertIn("Keywords=files;file management;Explorer;", main)
        self.assertIn("Dolphin;", main.split("Keywords=", 1)[1].splitlines()[0])
        self.assertIn("Keywords[tr]=dosyalar;dosya yönetimi;Explorer;", main)
        self.assertNotIn("GenericName", main)
        self.assertTrue(text.startswith("# Generated by veltos-desktop"))

    def test_hide_replaces_nodisplay(self):
        text = app_names.rewrite(VIM, "vim", hide=True)
        self.assertEqual(text.count("NoDisplay="), 1)
        self.assertIn("NoDisplay=true", text)

    def test_keywords_added_when_missing(self):
        text = app_names.rewrite(VIM, "vim", ("Text", "Metin", "Notepad;"))
        self.assertIn("Keywords=Notepad;Vim;", text)

    def test_exec_options_in_every_exec_line(self):
        text = app_names.rewrite(DOLPHIN, "dolphin", exec_options="--notransparency")
        self.assertEqual(text.count("Exec=dolphin --notransparency %u"), 2)
        konsole = "[Desktop Entry]\nName=Konsole\nExec=konsole\n\n[Desktop Action NewTab]\nExec=konsole --new-tab\n"
        text = app_names.rewrite(konsole, "konsole", ("Terminal", "Terminal", "cmd;"),
                                 exec_options=app_names.EXEC_OPTIONS["org.kde.konsole.desktop"])
        self.assertIn("\nExec=konsole --notransparency\n", text)
        self.assertIn("\nExec=konsole --notransparency --new-tab\n", text)

    def test_office_entries_start_the_veltos_office_screen(self):
        writer = ("[Desktop Entry]\nName=LibreOffice Writer\nExec=libreoffice --writer %U\n\n"
                  "[Desktop Action NewDocument]\nName=New Document\nExec=libreoffice --writer\n")
        text = app_names.rewrite(writer, "writer", ("Word Processor", "Kelime İşlemci", "Word;"),
                                 exec_options="--nologo", exec_replace=app_names.EXEC_REPLACE["libreoffice-writer.desktop"])
        self.assertIn("\nExec=veltos-office word %U\n", text)
        self.assertIn("\nExec=veltos-office word --blank\n", text)
        self.assertNotIn("--nologo", text)
        # Without the start screen installed the old line keeps its option.
        text = app_names.rewrite(writer, "writer", exec_options="--nologo")
        self.assertIn("\nExec=libreoffice --nologo --writer %U\n", text)
        self.assertIn("\nExec=libreoffice --nologo --writer\n", text)

    def test_spectacle_loses_its_shortcuts(self):
        spectacle = ("[Desktop Entry]\nName=Spectacle\nExec=/usr/bin/spectacle\nX-KDE-Shortcuts=Print,Meta+Shift+S\n"
                     "\n[Desktop Action FullScreenScreenShot]\nExec=/usr/bin/spectacle -f\nX-KDE-Shortcuts=Shift+Print\n")
        with tempfile.TemporaryDirectory() as tmp:
            src, out = Path(tmp) / "src", Path(tmp) / "xdg" / "applications"
            src.mkdir()
            (src / "org.kde.spectacle.desktop").write_text(spectacle, encoding="utf-8")
            app_names.update(src, out)
            copy = (out / "org.kde.spectacle.desktop").read_text(encoding="utf-8")
            self.assertNotIn("X-KDE-Shortcuts", copy)
            self.assertIn("NoDisplay=true", copy)
            off = (Path(tmp) / "xdg/kglobalaccel/org.kde.spectacle.desktop").read_text(encoding="utf-8")
            self.assertIn("\nNoDisplay=true\n", off)
            (src / "org.kde.spectacle.desktop").unlink()       # Spectacle removed
            app_names.update(src, out)
            self.assertFalse((Path(tmp) / "xdg/kglobalaccel/org.kde.spectacle.desktop").exists())

    def test_file_without_name_is_rejected(self):
        with self.assertRaises(ValueError):
            app_names.rewrite("[Desktop Entry]\nExec=x\n", "x", hide=True)

    def test_update_writes_installed_apps_and_drops_stale(self):
        with tempfile.TemporaryDirectory() as tmp:
            src, out = Path(tmp) / "src", Path(tmp) / "out"
            src.mkdir()
            out.mkdir()
            (src / "org.kde.dolphin.desktop").write_text(DOLPHIN, encoding="utf-8")
            (src / "vim.desktop").write_text(VIM, encoding="utf-8")
            (src / "winetricks.desktop").write_text("[Desktop Entry]\nExec=x\n", encoding="utf-8")
            (out / "old-app.desktop").write_text("stale")
            (out / "org.kde.kate.desktop").write_text("kate was removed")
            written = app_names.update(src, out)
            self.assertEqual(sorted(written), ["org.kde.dolphin.desktop", "vim.desktop"])
            self.assertEqual(sorted(p.name for p in out.iterdir()),
                             ["org.kde.dolphin.desktop", "vim.desktop"])

    def test_kde_file_manager_and_control_panel_hidden(self):
        # VeltOS File Explorer and VeltOS Settings replace them in Start.
        self.assertIn("org.kde.dolphin.desktop", app_names.HIDE)
        self.assertIn("systemsettings.desktop", app_names.HIDE)

    def test_default_apps_follow_installed_veltos_apps(self):
        with tempfile.TemporaryDirectory() as tmp:
            src, out = Path(tmp) / "src", Path(tmp) / "out"
            src.mkdir()
            app_names.update(src, out)
            self.assertFalse((out / "kde-mimeapps.list").exists())
            (src / "veltos-notepad.desktop").write_text("[Desktop Entry]\nName=Notepad\n", encoding="utf-8")
            app_names.update(src, out)
            text = (out / "kde-mimeapps.list").read_text(encoding="utf-8")
            self.assertIn("[Default Applications]", text)
            self.assertIn("text/plain=veltos-notepad.desktop;", text)
            self.assertNotIn("application/pdf", text)
            (src / "veltos-pdf.desktop").write_text("[Desktop Entry]\nName=PDF Reader\n", encoding="utf-8")
            app_names.update(src, out)
            text = (out / "kde-mimeapps.list").read_text(encoding="utf-8")
            self.assertIn("application/pdf=veltos-pdf.desktop;", text)
            (src / "veltos-notepad.desktop").unlink()
            (src / "veltos-pdf.desktop").unlink()
            app_names.update(src, out)
            self.assertFalse((out / "kde-mimeapps.list").exists())

    def test_hidden_apps_keep_their_windows_names(self):
        # KDE Info Center is hidden like Windows' (Settings > About opens
        # instead) but keeps its Windows name where it still shows.
        self.assertIn("org.kde.kinfocenter.desktop", app_names.HIDE)
